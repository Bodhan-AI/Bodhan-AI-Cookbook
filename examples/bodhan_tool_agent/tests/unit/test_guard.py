"""
Unit tests for Indic script guard (src/bodhan_agent/guard.py).
Ensures the LLM cannot output Indian-language text.
"""
import pytest
from bodhan_agent.guard import check, assert_safe


def test_guard_pure_english():
    text = "This is a clean English summary of the document."
    passed, count = check(text)
    assert passed is True
    assert count == 0


def test_guard_allowance_quoted_proper_noun():
    # A couple of Devanagari characters within allowance
    text = "The user mentioned the city of दिल्ली in the query."
    passed, count = check(text, allowance=10)
    assert passed is True
    assert count > 0


def test_guard_blocks_indic_text():
    # Long Hindi text generated by an LLM
    text = "यह एक परीक्षण है जो यह सुनिश्चित करता है कि भारतीय भाषा का पाठ पकड़ा गया है।"
    passed, count = check(text, allowance=5)
    assert passed is False
    assert count > 20


def test_guard_assert_safe_raises():
    text = "આ એક ગુજરાતી વાક્ય છે"
    with pytest.raises(ValueError, match="Script guard"):
        assert_safe(text, context="test")


def test_guard_assert_safe_passes():
    text = "All translation and transcription completed successfully."
    # Should not raise
    assert_safe(text, context="test")
