"""Pydantic schemas for MCP tool inputs, outputs, and structured results."""

from __future__ import annotations

from typing import Any, Literal
from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# 1. Transcribe Audio
# ---------------------------------------------------------------------------

class TranscribeAudioInput(BaseModel):
    file_path: str = Field(
        ...,
        description="Absolute or relative local file path to the audio file (WAV, MP3, M4A, OGG, AAC, FLAC).",
    )
    language: str | None = Field(
        None,
        description="Optional ISO language code (e.g. 'hi', 'ta', 'te', 'mr', 'en'). Omit for automatic detection.",
    )
    timestamp_granularities: list[str] | None = Field(
        None,
        description="Optional list of granularities, e.g. ['segment'] or ['word'] when available.",
    )


class AudioChunkTranscript(BaseModel):
    chunk_index: int
    start_time_s: float
    end_time_s: float
    text: str


class TranscribeAudioOutput(BaseModel):
    success: bool
    text: str = Field(..., description="Complete aggregated transcript in original sequence.")
    language: str = Field(..., description="Detected or specified ISO language code.")
    duration_seconds: float = Field(..., description="Total audio duration in seconds.")
    chunks: list[AudioChunkTranscript] = Field(default_factory=list, description="Per-chunk breakdown.")
    estimated_cost_inr: float = Field(..., description="Estimated cost in INR based on audio duration.")
    error: str | None = None


# ---------------------------------------------------------------------------
# 2. Translate Text
# ---------------------------------------------------------------------------

class TranslateTextInput(BaseModel):
    text: str = Field(..., description="The source text to translate.")
    target_language: str = Field(
        ...,
        description="Target ISO language code (e.g. 'hi', 'ta', 'te', 'bn', 'mr', 'en').",
    )
    script: Literal["native", "roman", "codemix"] = Field(
        "native",
        description="Desired output script: 'native' (default), 'roman' (Latin letters), or 'codemix' (conversational mix).",
    )
    preserve_formatting: bool = Field(
        True,
        description="Whether to preserve Markdown headings, tables, bullet points, and paragraph structure.",
    )


class TranslateTextOutput(BaseModel):
    success: bool
    translation: str = Field(..., description="The translated text.")
    target_language: str
    script: str
    truncated: bool = False
    source_char_count: int
    output_char_count: int
    estimated_cost_inr: float = Field(..., description="Estimated cost in INR based on output tokens.")
    error: str | None = None


# ---------------------------------------------------------------------------
# 3. Synthesize Speech
# ---------------------------------------------------------------------------

class SynthesizeSpeechInput(BaseModel):
    text: str = Field(..., description="Text to synthesize into speech.")
    language: str = Field(..., description="ISO language code of the text (e.g. 'hi', 'ta', 'bn').")
    voice: str | None = Field(
        None,
        description="Voice name matching language (e.g. 'Kavya', 'Amit', 'Anitha', 'Sourav'). Defaults to language default female voice.",
    )
    gender_preference: Literal["female", "male"] = Field(
        "female",
        description="Preferred gender if voice name is omitted: 'female' or 'male'.",
    )
    style: str | None = Field(
        None,
        description="Speaking delivery style (e.g. 'news', 'children\\'s stories', 'educational lecture', 'happy').",
    )
    output_file_path: str | None = Field(
        None,
        description="Optional destination path for the generated WAV file. Defaults to outputs/generated_speech_<timestamp>.wav.",
    )


class SynthesizeSpeechOutput(BaseModel):
    success: bool
    audio_file_path: str = Field(..., description="Path to the saved WAV audio file.")
    duration_seconds: float = Field(..., description="Duration of synthesized audio in seconds.")
    language: str
    voice: str
    style: str | None = None
    ai_generated_label: str = Field(
        "Notice: This audio was generated by Bodhan Indic-Speak AI synthesis.",
        description="Mandatory AI-generated speech disclosure.",
    )
    estimated_cost_inr: float = Field(..., description="Estimated cost in INR based on audio length.")
    error: str | None = None


# ---------------------------------------------------------------------------
# 4. Extract Text from Document (OCR)
# ---------------------------------------------------------------------------

class ExtractTextFromDocumentInput(BaseModel):
    file_path: str = Field(
        ...,
        description="Local path to the document image (PNG, JPG, JPEG) or multi-page PDF.",
    )
    table_format: Literal["markdown", "html"] = Field(
        "markdown",
        description="Table extraction format: 'markdown' (standard) or 'html' (complex/merged cells).",
    )


class PageOCROutput(BaseModel):
    page_number: int
    text: str
    blocks_count: int = 0
    blocks: list[dict[str, Any]] = Field(default_factory=list)
    success: bool = True
    error: str | None = None


class ExtractTextFromDocumentOutput(BaseModel):
    success: bool
    text: str = Field(..., description="Complete extracted Markdown text across all pages.")
    total_pages: int
    successful_pages: int
    failed_pages: int
    pages: list[PageOCROutput] = Field(default_factory=list)
    estimated_cost_inr: float = Field(..., description="Estimated cost in INR based on page count.")
    error: str | None = None
