def t(key: str, default: str = None) -> str:
    """
    Look up the localized string for `key` based on the user's preferred language.
    Falls back to English if the translation is missing.
    """
    lang = "en"
    if st is not None and hasattr(st, "session_state"):
        lang = st.session_state.get("preferred_language", "en") or "en"
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS["en"])

    if key in lang_dict:
        return lang_dict[key]

    # Fall back to English
    en_dict = TRANSLATIONS["en"]
    if key in en_dict:
        return en_dict[key]

    return default if default is not None else key
