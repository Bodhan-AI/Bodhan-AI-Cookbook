"""Build a versatility test video: two speakers, numbers, a music bed, a music-only gap and
a long stretch of nonstop speech. It exercises what the demo lesson doesn't: the male/female
voice switch, ducking under music, no narration over music-only parts, and forced chunk cuts.

    python scripts/make_test_video.py sample_data/two_speakers_music.mp4

The speech is generated by Indic-Speak's English voices (Bodhan models only; about ₹1), so the
video is original and free to use. The music is synthesised here. Output stays in sample_data/,
which is git-ignored.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import numpy as np
from dotenv import find_dotenv, load_dotenv

from bodhan_dub import audio, logs
from bodhan_dub.bodhan import BodhanClient
from bodhan_dub.cache import DiskCache
from bodhan_dub.config import Settings

RATE = 24_000
FEMALE, MALE = "Kavya", "Amit"
GAP_S = 0.6
SCRIPT: list[tuple[str, str | None]] = [
    ("music", None),
    (FEMALE, "Welcome back to Money Matters. Today we look at how compound interest really works."),
    (MALE, "Thanks for having me. Suppose you invest 50,000 rupees at 8 percent a year."),
    (FEMALE, "After one year, how much do you have?"),
    (MALE, "You have 54,000 rupees. In the second year, the interest itself starts earning interest."),
    ("music", None),
    # Nonstop: these sentences are joined with almost no pause, longer than one 15 s chunk.
    (FEMALE, "Here is the rule of 72. Divide 72 by the interest rate to estimate how many years it takes "
             "to double your money.|At 8 percent that is about 9 years, and at 12 percent it is about 6 years.|"
             "Banks often quote between 6.5 and 7.5 percent for fixed deposits, so doubling takes roughly 10 to "
             "11 years.|In 2023, inflation near 5 percent ate into that, so the real return was much smaller "
             "than it looked."),
    (MALE, "So the earlier you start, the better. Thanks for listening."),
    ("music", None),
]


def music(seconds: float, rate: int = RATE) -> np.ndarray:
    """A soft chord loop with a light pulse: clearly music, clearly not speech."""
    t = np.arange(int(seconds * rate)) / rate
    chords = [(220.0, 277.2, 329.6), (196.0, 246.9, 293.7), (174.6, 220.0, 261.6), (196.0, 246.9, 311.1)]
    out = np.zeros_like(t)
    for i, chord in enumerate(chords * int(seconds // 8 + 1)):
        a, b = i * 2.0, (i + 1) * 2.0
        sel = (t >= a) & (t < b)
        env = np.minimum(1.0, (t[sel] - a) * 4) * np.exp(-(t[sel] - a) * 0.8)
        out[sel] += sum(np.sin(2 * np.pi * f * t[sel]) for f in chord) * env
    pulse = (np.sin(2 * np.pi * 2.0 * t) > 0.95) * np.random.default_rng(0).normal(0, 0.3, len(t))
    out = out + pulse
    return (0.08 * out / np.max(np.abs(out))).astype(np.float32)


def main(out_path: Path) -> int:
    load_dotenv(find_dotenv(usecwd=True))
    logs.configure("WARNING")
    client = BodhanClient(Settings.from_env(), cache=DiskCache(out_path.parent / ".make_test_video_cache"))
    pieces: list[np.ndarray] = []
    for voice, text in SCRIPT:
        if voice == "music":
            pieces.append(np.zeros(int(6.0 * RATE), dtype=np.float32))  # music only: the bed fills it
            continue
        clips = []
        for sentence in text.split("|"):
            samples, rate = audio.wav_to_array(client.speak(sentence, voice, "en"))
            clips.append(audio.trim_silence(samples, rate))
            clips.append(np.zeros(int(0.08 * RATE), dtype=np.float32))  # too short to count as a pause
        pieces += [*clips, np.zeros(int(GAP_S * RATE), dtype=np.float32)]
    speech = np.concatenate(pieces)
    speech *= 0.5 / max(1e-6, float(np.max(np.abs(speech))))
    track = speech + music(len(speech) / RATE)[: len(speech)]
    wav = out_path.with_suffix(".wav")
    wav.write_bytes(audio.array_to_wav(track, RATE))
    seconds = len(track) / RATE
    subprocess.run(["ffmpeg", "-nostdin", "-y", "-v", "error", "-f", "lavfi", "-i",
                    f"testsrc2=size=640x360:rate=25:duration={seconds:.3f}", "-i", str(wav),
                    "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest", str(out_path)], check=True)
    wav.unlink()
    print(f"{out_path}: {seconds:.1f} s, cost ₹{client.usage.snapshot()['total_cost_inr']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1] if len(sys.argv) > 1 else "sample_data/two_speakers_music.mp4")))
