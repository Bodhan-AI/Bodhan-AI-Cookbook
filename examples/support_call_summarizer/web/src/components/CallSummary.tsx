import type { CallAnalysis, Resolution, Sentiment, SentimentTrend } from "../api";
import { SentimentChip } from "./SentimentChip";

const RESOLUTION_LABELS: Record<Resolution, string> = {
  resolved: "Resolved",
  partially_resolved: "Partly resolved",
  unresolved: "Unresolved",
  unclear: "Unclear",
};

const TREND_LABELS: Record<SentimentTrend, string> = {
  improved: "Improved during the call",
  steady: "Steady during the call",
  worsened: "Worsened during the call",
};

export function formatScore(score: number): string {
  return `${score > 0 ? "+" : ""}${score.toFixed(2)}`;
}

export function CallSummary({ analysis }: { analysis: CallAnalysis }) {
  const sentiment: Sentiment = analysis.overall_sentiment;

  return (
    <section className="card call-summary" aria-labelledby="summary-heading">
      <div className="call-summary__header">
        <h3 id="summary-heading" className="card__subtitle">
          AI summary
        </h3>
        <span className={`badge badge--resolution-${analysis.resolution}`}>{RESOLUTION_LABELS[analysis.resolution]}</span>
      </div>

      <p className="call-summary__text">{analysis.summary}</p>

      <dl className="call-summary__facts">
        {analysis.customer_issue && (
          <div className="call-summary__fact">
            <dt>Customer issue</dt>
            <dd>{analysis.customer_issue}</dd>
          </div>
        )}
        <div className="call-summary__fact">
          <dt>Customer sentiment</dt>
          <dd className="call-summary__sentiment">
            <SentimentChip sentiment={sentiment} />
            <span className="call-summary__score" title="From -1 (very negative) to +1 (very positive)">
              {formatScore(analysis.sentiment_score)}
            </span>
            <span className="call-summary__trend">{TREND_LABELS[analysis.customer_sentiment_trend]}</span>
          </dd>
          {analysis.sentiment_explanation && <dd className="call-summary__note">{analysis.sentiment_explanation}</dd>}
        </div>
        {analysis.action_items.length > 0 && (
          <div className="call-summary__fact">
            <dt>Action items</dt>
            <dd>
              <ul className="call-summary__list">
                {analysis.action_items.map((item, i) => (
                  <li key={i}>{item}</li>
                ))}
              </ul>
            </dd>
          </div>
        )}
        {analysis.topics.length > 0 && (
          <div className="call-summary__fact">
            <dt>Topics</dt>
            <dd className="call-summary__topics">
              {analysis.topics.map((topic) => (
                <span key={topic} className="topic-chip">
                  {topic}
                </span>
              ))}
            </dd>
          </div>
        )}
      </dl>

      <p className="call-summary__footnote">Generated by {analysis.model}. AI output can be wrong; check the transcript.</p>
    </section>
  );
}
